// Compiles every theme in themes/ for every screen size, with the same
// compiler the device's Sleep Themes page runs, and writes dist/:
//   dist/index.json
//   dist/<WxH>/<id>/{theme.bin, bg.bmp, mask.bmp (overlay only), front.bmp (art over images),
//                    f0..f3.cpfont, preview.png}
//
//   node tools/compile.mjs [id ...]      (all themes when none are given)
//
// The compiler is tools/compiler/SleepThemesPage.html, a copy of the firmware's
// page (tools/sync-compiler.sh refreshes it). It runs unmodified: this script
// serves it with a stand-in /api/sleep-theme/vars for each screen size, hands
// it the theme folder, and collects what its Compile button would install.
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { serve, launch } from './browser.mjs';
import { listThemes, themeFiles } from './themes.mjs';

// Build keys are the panel's native size, long side first.
const BUILDS = { '800x480': [800, 480], '792x528': [792, 528] };
// Sample values are taken at a fixed time so previews don't change run to run.
const SAMPLE_NOW = Date.UTC(2026, 9, 17, 22, 41) / 1000;

const only = process.argv.slice(2);
const themes = listThemes().filter((t) => !only.length || only.includes(t.id));
const browser = await launch();

// ---- From the bench: sample values, icon fonts and icon SVGs -----------------
const benchServer = await serve('bench');
const bench = await browser.newPage();
await bench.goto(benchServer.url + '/index.html', { waitUntil: 'networkidle0' });
const vars = await bench.evaluate((now) => {
  const kinds = { n: 'number', t: 'text', ts: 'timestamp', img: 'image' };
  return VARS.map(([name, k]) => {
    let raw = rawOf(name);
    if (name === 'time.now') raw = now;
    const v = { name, kind: kinds[k], value: '' };
    if (k === 'img' || raw === null || raw === undefined || raw === '') return v;
    v.value = k === 'ts' ? formatDate(raw, name === 'time.now' ? 'HH:mm' : 'yyyy-MM-dd') : String(raw);
    if (k === 'n' || k === 'ts') v.raw = Number(raw);
    return v;
  });
}, SAMPLE_NOW);

const b64 = (buf) => Buffer.from(buf).toString('base64');
async function benchFile(fn, arg) {
  return Buffer.from(await bench.evaluate(fn, arg), 'base64');
}
// icons-<set>.otf, generated by the bench's icon-font maker.
const iconFont = (key) => benchFile(async (k) => {
  const bytes = new Uint8Array(await buildIconFont(k).arrayBuffer());
  let s = '';
  for (const b of bytes) s += String.fromCharCode(b);
  return btoa(s);
}, key);
// icons/<name>.svg for icon("name"), from the bench's Lucide set.
const iconSvg = (name) => benchFile((n) => {
  const src = findIcon(n);
  return src ? btoa(iconSvgText(src)) : '';
}, name);

// The theme folder, plus what it uses but the bench supplies: Inter, icon
// fonts and Lucide icons.
async function filesFor(id) {
  const files = {};
  for (const path of themeFiles(id)) {
    if (path === 'theme.json') continue;
    files[path] = readFileSync(join('themes', id, path));
  }
  const html = files['theme.html'].toString('utf8');
  for (const font of ['Inter-Regular.ttf', 'Inter-Bold.ttf']) {
    if (html.includes(font) && !files[font]) files[font] = readFileSync(join('fonts', font));
  }
  for (const m of html.matchAll(/icons-(moons|dots|stars|ticks)\.otf/g)) {
    if (!files[m[0]]) files[m[0]] = await iconFont(m[1]);
  }
  for (const m of html.matchAll(/icon\(\s*(?:"|&quot;|')([A-Za-z0-9_-]+)(?:"|&quot;|')\s*\)/g)) {
    const path = `icons/${m[1]}.svg`;
    if (files[path]) continue;
    const svg = await iconSvg(m[1]);
    if (!svg.length) throw new Error(`${id}: no icon called "${m[1]}"`);
    files[path] = svg;
  }
  return files;
}

// ---- The compiler -----------------------------------------------------------
let current = null; // the build being compiled: [width, height]
// A theme's sample plugin values (theme.json "samples": {"plugin.<name>.<key>": "text"}),
// served like a device with that plugin installed, so its store preview isn't
// blank. Only plugin.* names: every other value comes from the bench, as on a device.
let samples = [];
const PLUGIN_VAR = /^plugin\.[A-Za-z0-9_]+\.[A-Za-z0-9_]+$/;
const compilerServer = await serve('tools/compiler', {
  '/': (req, res) => res.writeHead(200, { 'content-type': 'text/html' }).end(readFileSync('tools/compiler/SleepThemesPage.html')),
  '/api/sleep-theme/vars': (req, res) => {
    const [panelWidth, panelHeight] = current;
    const body = { panelWidth, panelHeight, themesDir: '/sleep-themes', formatVersion: 1,
      limits: { elements: 64, fonts: 4, strings: 4096 }, active: '', vars: vars.concat(samples) };
    res.writeHead(200, { 'content-type': 'application/json' }).end(JSON.stringify(body));
  },
  '/api/files': (req, res) => res.writeHead(200, { 'content-type': 'application/json' }).end('[]'),
});

const page = await browser.newPage();
await page.setRequestInterception(true);
// Only the local server: the page's store and fonts would reach the internet.
page.on('request', (r) => (r.url().startsWith(compilerServer.url) || r.url().startsWith('data:') || r.url().startsWith('blob:') ? r.continue() : r.abort()));
page.on('pageerror', (e) => console.error('  page error:', e.message));

const index = { version: 1, themes: [] };
let failed = 0;
for (const t of themes) {
  const entry = { id: t.id, name: t.name, description: t.description, orientation: t.orientation, overlay: t.overlay, builds: {} };
  // A plugin the theme needs (theme.json "requires": {plugin, name, url}): the
  // device and the web store say so, and where to get it.
  if (t.requires) {
    const { plugin, name, url } = t.requires;
    if (!/^[a-z0-9][a-z0-9-]{0,30}$/.test(plugin || '')) throw new Error(`${t.id}: requires.plugin "${plugin}" is not a plugin folder name`);
    entry.requires = { plugin, name: name || plugin, ...(url ? { url } : {}) };
  }
  const files = await filesFor(t.id);
  samples = Object.entries(t.samples || {})
    .filter(([name]) => PLUGIN_VAR.test(name))
    .map(([name, value]) => ({ name, kind: 'text', value: String(value) }));
  const payload = Object.fromEntries(Object.entries(files).map(([p, buf]) => [p, b64(buf)]));
  for (const [key, size] of Object.entries(BUILDS)) {
    current = size;
    await page.goto(compilerServer.url + '/', { waitUntil: 'networkidle0' });
    await page.waitForFunction(() => typeof device !== 'undefined' && device !== null);
    const out = await page.evaluate(async (id, payload) => {
      const map = new Map();
      for (const [path, data] of Object.entries(payload)) {
        const bin = atob(data);
        const bytes = new Uint8Array(bin.length);
        for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
        map.set(path, new Blob([bytes]));
      }
      setFiles(map, id);
      try {
        await compile();
      } catch (e) {
        return { error: e.message };
      }
      if (!compiled) return { error: [...document.querySelectorAll('#log .err')].map((e) => e.textContent).join('; ') || 'not compiled' };
      const enc = (u8) => { let s = ''; for (const b of u8) s += String.fromCharCode(b); return btoa(s); };
      const canvases = [...document.querySelectorAll('#previews canvas')];
      // An overlay's preview goes on a stand-in book page, through its mask,
      // so the store shows what it looks like over your reading.
      if (compiled.mask && canvases[1] && canvases[2]) {
        const w = canvases[1].width, h = canvases[1].height;
        const out = document.createElement('canvas');
        out.width = w;
        out.height = h;
        const ctx = out.getContext('2d');
        ctx.fillStyle = '#fff';
        ctx.fillRect(0, 0, w, h);
        ctx.fillStyle = '#000';
        const m = Math.round(w * 0.08);
        let seed = 7;
        const rnd = () => (seed = (seed * 9301 + 49297) % 233280) / 233280;
        for (let y = m + 60, i = 0; y < h - m - 30; y += 26, i++) {
          const indent = i % 9 === 0 ? 28 : 0;
          const len = i % 9 === 8 ? (w - 2 * m) * (0.3 + rnd() * 0.4) : w - 2 * m - indent - rnd() * 12;
          for (let x = m + indent; x < m + indent + len; ) {
            const word = 18 + rnd() * 54;
            ctx.fillRect(x, y, Math.min(word, m + indent + len - x), 7);
            x += word + 8;
          }
        }
        const page = ctx.getImageData(0, 0, w, h);
        const p = canvases[1].getContext('2d').getImageData(0, 0, w, h).data;
        const k = canvases[2].getContext('2d').getImageData(0, 0, w, h).data;
        for (let i = 0; i < p.length; i += 4) {
          if (k[i] < 128) for (let c = 0; c < 4; c++) page.data[i + c] = p[i + c];
        }
        ctx.putImageData(page, 0, 0);
        canvases[1] = out;
      }
      // The preview sits in a light reader bezel, so a white screen (Blank, the
      // light themes) still has an edge on a white page: the README gallery and
      // the web store show these.
      if (canvases[1]) {
        const screen = canvases[1];
        const B = 18;
        const framed = document.createElement('canvas');
        framed.width = screen.width + 2 * B;
        framed.height = screen.height + 2 * B;
        const ctx = framed.getContext('2d');
        ctx.fillStyle = '#e4e4e4';
        ctx.strokeStyle = '#a8a8a8';
        ctx.lineWidth = 2;
        ctx.beginPath();
        ctx.roundRect(1, 1, framed.width - 2, framed.height - 2, 14);
        ctx.fill();
        ctx.stroke();
        ctx.drawImage(screen, B, B);
        ctx.strokeStyle = '#bdbdbd';
        ctx.lineWidth = 1;
        ctx.strokeRect(B - 0.5, B - 0.5, screen.width + 1, screen.height + 1);
        canvases[1] = framed;
      }
      return {
        themeBin: enc(compiled.themeBin),
        bmp: enc(compiled.bmp),
        mask: compiled.mask ? enc(compiled.mask) : null,
        front: compiled.front ? enc(compiled.front) : null,
        fonts: compiled.fontFiles.map(enc),
        preview: canvases[1] ? canvases[1].toDataURL('image/png').split(',')[1] : null,
      };
    }, t.id, payload);

    const dir = join('dist', key, t.id);
    rmSync(dir, { recursive: true, force: true });
    if (out.error) {
      console.error(`FAIL ${key} ${t.id}: ${out.error}`);
      failed++;
      continue;
    }
    mkdirSync(dir, { recursive: true });
    // The build's version is a hash of what the device downloads: its store
    // client offers an update when it changes. Builds are deterministic, so
    // an untouched theme keeps its version.
    const hash = createHash('sha256');
    const write = (name, data, versioned = true) => {
      const buf = Buffer.from(data, 'base64');
      writeFileSync(join(dir, name), buf);
      if (versioned) hash.update(name).update(buf);
      return { name, size: buf.length };
    };
    // theme.bin last in the list: the store client writes it last, so a
    // half-installed theme is never picked up.
    const list = [write('bg.bmp', out.bmp)];
    if (out.mask) list.push(write('mask.bmp', out.mask));
    if (out.front) list.push(write('front.bmp', out.front));
    out.fonts.forEach((f, i) => list.push(write(`f${i}.cpfont`, f)));
    list.push(write('theme.bin', out.themeBin));
    if (out.preview) write('preview.png', out.preview, false);
    if (t.overlay && !out.mask) {
      console.error(`FAIL ${key} ${t.id}: overlay theme compiled without a mask (is tools/compiler up to date?)`);
      failed++;
      continue;
    }
    entry.builds[key] = { version: hash.digest('hex').slice(0, 12), files: list };
    const kb = Math.round(list.reduce((n, f) => n + f.size, 0) / 1024);
    console.log(`ok   ${key} ${t.id} (${list.length} files, ${kb} KB)`);
  }
  if (Object.keys(entry.builds).length) index.themes.push(entry);
}

// Keep entries for themes not rebuilt this run.
if (only.length && existsSync('dist/index.json')) {
  const old = JSON.parse(readFileSync('dist/index.json', 'utf8'));
  for (const e of old.themes) if (!index.themes.some((t) => t.id === e.id)) index.themes.push(e);
  const order = new Map(listThemes().map((t, i) => [t.id, i]));
  index.themes.sort((a, b) => (order.get(a.id) ?? 1e9) - (order.get(b.id) ?? 1e9));
}
mkdirSync('dist', { recursive: true });
writeFileSync('dist/index.json', JSON.stringify(index, null, 2) + '\n');
console.log(`dist/index.json: ${index.themes.length} themes`);

await browser.close();
benchServer.close();
compilerServer.close();
process.exit(failed ? 1 : 0);
